/* ---------- পার্সার ---------- */
function parse() {
  const groups = [];
  let g = null, s = null, n = 0;
  for (const line of RAW.split("\n").map(x => x.trim()).filter(Boolean)) {
    if (line.startsWith("## ")) {
      g = { title: line.slice(3), sections: [] };
      groups.push(g);
    } else if (line.startsWith("★")) {
      const need = (line.match(/\{need=(\d+)\}/) || [])[1];
      const title = line.replace(/\{need=\d+\}/, "").replace(/^★\s*/, "").replace(/\s*★\s*$/, "").trim();
      s = { title, need: need ? +need : 0, items: [] };
      g.sections.push(s);
    } else if (line.startsWith("☐")) {
      const strong = (line.match(/\{strong=(\d+)\}/) || [])[1];
      const text = line.replace(/\{strong=\d+\}/, "").replace(/^☐\s*/, "").trim();
      s.items.push({ id: "c" + n++, text, strong: strong ? +strong : 0 });
    }
  }
  return groups;
}

const toBn = x => String(x).replace(/\d/g, d => "০১২৩৪৫৬৭৮৯"[d]);

/* ---------- রেন্ডার ----------
   mountSymptomChecklist(card, { checked: string[], onSave: async(ids)=>void, patient: {name, meta}, back: url }) */
export function mountSymptomChecklist(card, opt) {
  const groups = parse(), all = groups.flatMap(g => g.sections);
  const total = all.reduce((a, s) => a + s.items.length, 0);
  const sel = new Set(opt.checked || []);
  const el = (tag, css, txt) => { const e = document.createElement(tag); if (css) e.style.cssText = css; if (txt != null) e.textContent = txt; return e; };

  card.innerHTML = "";
  card.style.maxWidth = "720px";
  card.appendChild(el("h2", "margin:0 0 6px;font-size:20px;color:var(--primary-color,#4f46e5)", "🩺 Symptom Diagnosis"));
  card.appendChild(el("div", "font-weight:700;font-size:15px", opt.patient.name || "Patient"));
  if (opt.patient.meta) card.appendChild(el("div", "font-size:12px;color:#64748b;margin-bottom:10px", opt.patient.meta));

  const result = el("div", "position:sticky;top:0;z-index:5;background:#fff;border:1px solid #c7d2fe;border-radius:10px;padding:10px 12px;margin:8px 0 14px;font-size:13px;box-shadow:0 2px 8px rgba(0,0,0,.08)");
  card.appendChild(result);

  const badges = new Map();
  for (const g of groups) {
    card.appendChild(el("h3", "margin:18px 0 8px;font-size:16px;padding-bottom:4px;border-bottom:2px solid #e2e8f0", g.title));
    for (const s of g.sections) {
      const box = el("div", "border:1px solid #e2e8f0;border-radius:10px;padding:10px 12px;margin:0 0 10px");
      const head = el("div", "display:flex;justify-content:space-between;gap:8px;align-items:flex-start;margin-bottom:6px");
      head.appendChild(el("div", "font-weight:700;font-size:14px", "★ " + s.title));
      const badge = el("span", "flex:none;font-size:12px;color:#475569;background:#f1f5f9;border-radius:99px;padding:2px 8px");
      head.appendChild(badge);
      box.appendChild(head);
      badges.set(s, badge);
      for (const it of s.items) {
        const lab = el("label", "display:flex;gap:8px;align-items:flex-start;padding:6px 0;font-size:14px;line-height:1.5;cursor:pointer");
        const cb = el("input", "flex:none;width:18px;height:18px;margin-top:3px");
        cb.type = "checkbox";
        cb.checked = sel.has(it.id);
        cb.onchange = () => { cb.checked ? sel.add(it.id) : sel.delete(it.id); update(); };
        lab.appendChild(cb);
        lab.appendChild(el("span", "", it.text));
        box.appendChild(lab);
      }
      card.appendChild(box);
    }
  }

  const row = el("div", "display:flex;gap:8px;align-items:center;margin-top:14px");
  const back = el("a", "flex:1;text-align:center;text-decoration:none;box-sizing:border-box", "Back");
  back.className = "c-no"; back.href = opt.back;
  const save = el("button", "flex:2", "Save");
  save.type = "button"; save.className = "rc-btn rc-btn-primary";
  row.appendChild(back); row.appendChild(save);
  card.appendChild(row);
  const st = el("div", "text-align:center;font-size:12px;margin-top:8px;min-height:16px");
  card.appendChild(st);

  function update() {
    const rows = [];
    let ticked = 0;
    for (const s of all) {
      const n = s.items.filter(i => sel.has(i.id)).length;
      ticked += n;
      badges.get(s).textContent = toBn(n) + "/" + toBn(s.items.length);
      badges.get(s).style.cssText = "flex:none;font-size:12px;border-radius:99px;padding:2px 8px;" +
        (n ? "background:#dcfce7;color:#166534;font-weight:700" : "background:#f1f5f9;color:#475569");
      if (n) rows.push({ s, n, p: Math.round(n / s.items.length * 100), strong: s.items.filter(i => sel.has(i.id) && i.strong).map(i => i.strong) });
    }
    rows.sort((a, b) => b.p - a.p || b.n - a.n);
    result.innerHTML = "";
    result.appendChild(el("div", "font-weight:700;margin-bottom:4px", "📊 ফলাফল — মোট টিক: " + toBn(ticked) + " / " + toBn(total)));
    if (!rows.length) { result.appendChild(el("div", "color:#64748b", "কোনো আলামত টিক দেওয়া হয়নি।")); return; }
    const list = el("div", "max-height:150px;overflow:auto");
    for (const r of rows) {
      const met = r.s.need && r.n >= r.s.need;
      let t = "• " + r.s.title + " — " + toBn(r.n) + "/" + toBn(r.s.items.length) + " (" + toBn(r.p) + "%)";
      if (r.s.need) t += met ? " ✅ শর্ত পূর্ণ (" + toBn(r.s.need) + "টি মিলেছে)" : " — শর্ত: " + toBn(r.s.need) + "টি দরকার";
      if (r.strong.length) t += " ⚠️ এই আলামত থাকলে " + toBn(Math.max(...r.strong)) + "% সম্ভাবনা";
      list.appendChild(el("div", "padding:2px 0;" + (met || r.strong.length ? "color:#166534;font-weight:700" : ""), t));
    }
    result.appendChild(list);
    result.appendChild(el("div", "font-size:11px;color:#94a3b8;margin-top:4px", "এটি আলামত মিলের হিসাব; চূড়ান্ত সিদ্ধান্ত নয়।"));
  }
  update();

  save.onclick = async () => {
    save.disabled = true;
    st.style.color = "#64748b"; st.textContent = "Saving...";
    try {
      await opt.onSave([...sel]);
      st.style.color = "#16a34a"; st.textContent = "✅ Saved";
    } catch (e) {
      console.error(e);
      st.style.color = "#dc2626"; st.textContent = "Save failed";
    }
    save.disabled = false;
  };
}
