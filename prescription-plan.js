/* ---------- তাশখিস থেকে সংকেত ---------- */
function analyse(symptomChecks, responseChecks) {
  const sy = symptomSummary(symptomChecks), re = responseSummary(responseChecks);
  const ticked = sy.filter(s => s.n > 0);
  const texts = ticked.flatMap(s => s.texts);
  let auto = "", best = 0;
  for (const [key, t] of TIME_SECS) {
    const s = sy.find(x => x.title.includes(key));
    if (s && s.n > 0 && s.n >= best) { best = s.n; auto = t; }
  }
  const khadem = sy.find(s => s.title.includes("খাদেম জিন চেনার"));
  const resText = re.map(r => r.result).join(" ");
  const has = ws => ticked.some(s => ws.some(w => s.title.includes(w)));
  const jinn = (khadem && khadem.n > 0) || /জ্বিনের আলামত|চালান জ্বিন শরীরে আছে|খাদেম/.test(resText);
  const stomach = ticked.some(s => s.title.includes("পেট")) || /পেটে/.test(resText);
  const away = texts.some(t => /বাড়ি আসে না|ঘর ছাড়ে/.test(t));
  const selfHarm = texts.some(t => t.includes("আত্মহত্যা"));
  const reactTexts = re.flatMap(r => r.reacts).join(" ");
  const outS = sy.filter(s => s.group.includes("বাহিরে")), inS = sy.filter(s => s.group.includes("শরীরে থাকা"));
  const outOn = outS.length === OUT.length ? outS.map(s => s.n > 0) : OUT.map(() => false);
  const inOn = inS.length === INN.length ? inS.map(s => s.n > 0) : INN.map(() => false);
  const placeOn = [
    has(["পেট"]) || /পেটে খাদেম|পেটে থাকা যাদু/.test(resText),
    has(["মাথায় থাকা", "ঘাড় ও কাঁধে", "মাথার সামনে", "ঘাড় ও পিছন"]) || /মাথায় খাদেম/.test(resText),
    has(["কোমর"]) || /কোমরে খাদেম/.test(resText),
    has(["হাত-পা বেঁধে", "পা, কাঁধ, হাতে", "রাস্তা বন্দি"]) || /পায়ে খাদেম|পা, কাঁধ, হাতে/.test(resText)
  ];
  const jabali = sy.some(s => s.title.includes("পাহাড়ি যাদুর") && s.need && s.n >= s.need) || /পাহাড়ি যাদুর আলামত/.test(resText);
  const hit = i => {
    const hasTxt = k => texts.some(t => k.some(w => t.includes(w)));
    if (i === 0) return outOn.some(Boolean);
    if (i === 6) return has(["কোমর", "পা বাঁধ", "পা বন্দি", "পা, কাঁধ"]) || /পা ভারী/.test(reactTexts);
    if (i === 7) return has(["বুক"]);
    if (i === 8) return has(["মাথায়", "মাথা"]) || /মাথা ভারী/.test(reactTexts);
    if (i === 9) return hasTxt(["ঘৃণা"]);
    return false;
  };
  return { sy, re, ticked, auto, jinn, stomach, away, selfHarm, hit, outOn, inOn, placeOn, jabali };
}

